"""Generate supabase/seed.sql and the web app's offline content copy from waste_content.json.

    python supabase/scripts/build_seed.py          # write seed.sql + web copy
    python supabase/scripts/build_seed.py --check  # fail if either is out of date (CI)

The seed upserts (insert ... on conflict do update), so it can be re-run safely.
The web copy (apps/web/src/content/waste_content.json) lets the scanner show items
before Supabase answers and while offline (Phases 12, 21).
"""

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CONTENT = ROOT / "content" / "waste_content.json"
SEED = ROOT / "seed.sql"
WEB_COPY = ROOT.parent / "apps" / "web" / "src" / "content" / "waste_content.json"


def q(value: object) -> str:
    """SQL literal for str / None / bool / int."""
    if value is None:
        return "null"
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, int):
        return str(value)
    return "'" + str(value).replace("'", "''") + "'"


def text_array(values: list[str]) -> str:
    return "array[" + ", ".join(q(v) for v in values) + "]::text[]" if values else "'{}'::text[]"


def build(content: dict) -> str:
    cats = content["categories"]
    items = content["items"]
    cat_keys = {c["key"] for c in cats}
    seen: set[str] = set()
    for it in items:
        if it["category"] not in cat_keys:
            sys.exit(f"{it['class_key']}: unknown category {it['category']}")
        if it["class_key"] in seen:
            sys.exit(f"duplicate class_key {it['class_key']}")
        seen.add(it["class_key"])

    out = [
        "-- GENERATED by supabase/scripts/build_seed.py from supabase/content/waste_content.json.",
        "-- Do not edit by hand. Re-run the script after changing the JSON.",
        "",
        "insert into public.waste_categories",
        "  (key, name, bin_label, bin_color, description, examples, ra9003_term, icon, sort_order)",
        "values",
    ]
    out.append(
        ",\n".join(
            "  ("
            + ", ".join(
                q(c[k])
                for k in (
                    "key",
                    "name",
                    "bin_label",
                    "bin_color",
                    "description",
                    "examples",
                    "ra9003_term",
                    "icon",
                    "sort_order",
                )
            )
            + ")"
            for c in cats
        )
    )
    out += [
        "on conflict (key) do update set",
        "  name = excluded.name, bin_label = excluded.bin_label, bin_color = excluded.bin_color,",
        "  description = excluded.description, examples = excluded.examples,",
        "  ra9003_term = excluded.ra9003_term, icon = excluded.icon,"
        " sort_order = excluded.sort_order;",
        "",
        "insert into public.waste_items",
        "  (class_key, display_name, display_name_fil, category_key, short_instruction, reuse_tip,",
        "   prep_steps, why_text, contamination_note, search_aliases, is_detectable, rule_source)",
        "values",
    ]
    rows = []
    for it in items:
        rows.append(
            "  ("
            + ", ".join(
                [
                    q(it["class_key"]),
                    q(it["display_name"]),
                    q(it.get("display_name_fil")),
                    q(it["category"]),
                    q(it["short_instruction"]),
                    q(it.get("reuse_tip")),
                    q(json.dumps(it.get("prep_steps", []), ensure_ascii=False)) + "::jsonb",
                    q(it.get("why_text")),
                    q(it.get("contamination_note")),
                    text_array(it.get("aliases", [])),
                    q(bool(it["detectable"])),
                    q(it.get("source")),
                ]
            )
            + ")"
        )
    out.append(",\n".join(rows))
    out += [
        "on conflict (class_key) do update set",
        "  display_name = excluded.display_name, display_name_fil = excluded.display_name_fil,",
        "  category_key = excluded.category_key, short_instruction = excluded.short_instruction,",
        "  reuse_tip = excluded.reuse_tip, prep_steps = excluded.prep_steps,",
        "  why_text = excluded.why_text, contamination_note = excluded.contamination_note,",
        "  search_aliases = excluded.search_aliases, is_detectable = excluded.is_detectable,",
        "  rule_source = excluded.rule_source;",
        "",
    ]
    return "\n".join(out)


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true", help="fail if seed.sql is stale")
    args = parser.parse_args()
    content = json.loads(CONTENT.read_text(encoding="utf-8"))
    sql = build(content)
    public = {k: v for k, v in content.items() if not k.startswith("_")}
    web = json.dumps(public, ensure_ascii=False, indent=1) + "\n"
    if args.check:
        stale = [
            str(path.relative_to(ROOT.parent))
            for path, text in ((SEED, sql), (WEB_COPY, web))
            if not path.exists() or path.read_text(encoding="utf-8") != text
        ]
        if stale:
            sys.exit(f"Out of date: {', '.join(stale)}. Run python supabase/scripts/build_seed.py")
        print("seed.sql and the web content copy are up to date")
        return
    SEED.write_text(sql, encoding="utf-8", newline="\n")
    WEB_COPY.parent.mkdir(parents=True, exist_ok=True)
    WEB_COPY.write_text(web, encoding="utf-8", newline="\n")
    print(f"Wrote {SEED.relative_to(ROOT.parent)} + web copy ({len(content['items'])} items)")


if __name__ == "__main__":
    main()
